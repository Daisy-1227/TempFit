# ---------------------------------------------------------------------------- #
#  Apply the dataset's val transform chain (VecClipping + VecGridSample test).
#
#  We *invoke* the project's own transform classes rather than re-implement
#  them — earlier attempts to re-implement diverged by ±1..4 lines on ~2% of
#  windows due to subtle edge cases. Calling the real classes guarantees
#  byte-exact alignment with the NPZ that was generated by the same pipeline.
# ---------------------------------------------------------------------------- #
def _apply_val_transforms(
    lines_norm: np.ndarray,
    prim_ids_per_line: np.ndarray,
    inst_per_prim: np.ndarray,
    sem_per_prim: np.ndarray,
    primitive_lengths: np.ndarray,
    min_instance_ratio: float,
    grid_size: float,
):
    """Return indices into the input `lines_norm` rows that survive the
    VecClipping + VecGridSample(test) chain — same order the model saw.
    """
    from datasets.transform import VecClipping, VecGridSample
    from datasets.vec_data.industrycad.dataclass_define import SVGData

    n = lines_norm.shape[0]
    if n == 0:
        return np.empty(0, dtype=np.int64)

    # Tag each line with its row index in `cols` so we can recover the mapping
    # after VecClipping reorders / filters via primitive_ids LUTs.
    # VecClipping operates per-line via `keep_mask`; VecGridSample picks one
    # representative per grid cell — both preserve a "which input row did this
    # output row come from" invariant we can extract by piggybacking on the
    # `colors` channel (free passenger).
    row_idx = np.arange(n, dtype=np.int64)
    colors_passenger = np.zeros((n, 3), dtype=np.float64)
    colors_passenger[:, 0] = row_idx  # carry idx in R channel

    svg = SVGData(
        viewBox=[0.0, 0.0, 30000.0, 30000.0],
        coords=lines_norm.astype(np.float32, copy=False),
        colors=colors_passenger,
        widths=np.ones(n, dtype=np.float32),
        layer_ids=np.zeros(n, dtype=np.int32),
        primitive_ids=prim_ids_per_line.astype(np.int32, copy=False),
        semantic_ids=sem_per_prim.astype(np.int32, copy=False),
        instance_ids=inst_per_prim.astype(np.int32, copy=False),
        primitive_lengths=primitive_lengths.astype(np.float32, copy=False),
    )
    n_inst = int(inst_per_prim.size)
    dd = {
        "svg_data": svg,
        "translation": np.zeros((n_inst, 2), dtype=np.float32),
        "size": np.ones((n_inst, 2), dtype=np.float32),
    }

    clip = VecClipping(
        clip_range=[-1, 1], min_instance_ratio=min_instance_ratio, update_size=True
    )
    dd = clip(dd)
    if dd.get("_drop_sample", False):
        return np.empty(0, dtype=np.int64)
    grid = VecGridSample(
        grid_size=grid_size, hash_type="fnv", mode="test", return_grid_coord=True
    )
    dd = grid(dd)

    out_colors = np.asarray(dd["svg_data"].colors)
    out_idx = np.rint(out_colors[:, 0]).astype(np.int64)
    return out_idx


# ---------------------------------------------------------------------------- #
#  FULL-line variant: post-VecClipping lines (no grid sample), every line
#  inherits the (assign_inst, assign_sem) of its grid cell's survivor.
# ---------------------------------------------------------------------------- #
def _fnv_hash_vec(arr: np.ndarray) -> np.ndarray:
    """FNV64-1A matching `VecGridSample.fnv_hash_vec` byte for byte."""
    arr = arr.astype(np.uint64, copy=True)
    h = np.uint64(14695981039346656037) * np.ones(arr.shape[0], dtype=np.uint64)
    for j in range(arr.shape[1]):
        h *= np.uint64(1099511628211)
        h = np.bitwise_xor(h, arr[:, j])
    return h


def _apply_clipping_with_inheritance(
    lines_norm: np.ndarray,
    prim_ids_per_line: np.ndarray,
    inst_per_prim: np.ndarray,
    sem_per_prim: np.ndarray,
    primitive_lengths: np.ndarray,
    min_instance_ratio: float,
    grid_size: float,
):
    """Run the real VecClipping + VecGridSample, but ALSO return the
    inheritance map from each post-clip line to its NPZ position.

    Returns:
      idx_post_clip:    (N1,) indices into input `lines_norm` that survived clipping
      idx_grid_in_post: (N2,) indices into idx_post_clip of the gridsample survivors
                        (NPZ's arrays are aligned to N2 in this order)
      npz_pos_per_post: (N1,) for each post-clip line, the position in NPZ whose
                        prediction it inherits (lines in same grid cell share)

    N1 = post-clip count (full set we want to render)
    N2 = post-grid count (matches NPZ.assign_inst.size)
    """
    from datasets.transform import VecClipping, VecGridSample
    from datasets.vec_data.industrycad.dataclass_define import SVGData

    n = lines_norm.shape[0]
    if n == 0:
        return (
            np.empty(0, dtype=np.int64),
            np.empty(0, dtype=np.int64),
            np.empty(0, dtype=np.int64),
        )

    # Passenger trick: carry row index in colors[:, 0]; survives both transforms.
    row_idx = np.arange(n, dtype=np.float64)
    colors = np.zeros((n, 3), dtype=np.float64)
    colors[:, 0] = row_idx

    svg = SVGData(
        viewBox=[0.0, 0.0, 30000.0, 30000.0],
        coords=lines_norm.astype(np.float32, copy=False),
        colors=colors,
        widths=np.ones(n, dtype=np.float32),
        layer_ids=np.zeros(n, dtype=np.int32),
        primitive_ids=prim_ids_per_line.astype(np.int32, copy=False),
        semantic_ids=sem_per_prim.astype(np.int32, copy=False),
        instance_ids=inst_per_prim.astype(np.int32, copy=False),
        primitive_lengths=primitive_lengths.astype(np.float32, copy=False),
    )
    n_inst = int(inst_per_prim.size)
    dd = {
        "svg_data": svg,
        "translation": np.zeros((n_inst, 2), dtype=np.float32),
        "size": np.ones((n_inst, 2), dtype=np.float32),
    }
    dd = VecClipping(
        clip_range=[-1, 1], min_instance_ratio=min_instance_ratio, update_size=True
    )(dd)
    if dd.get("_drop_sample", False):
        return (
            np.empty(0, dtype=np.int64),
            np.empty(0, dtype=np.int64),
            np.empty(0, dtype=np.int64),
        )

    # Snapshot post-clip state (BEFORE gridsample mutates it).
    post_clip_coords = np.asarray(dd["svg_data"].coords).copy()  # (N1, 2, 2)
    post_clip_colors = np.asarray(dd["svg_data"].colors).copy()
    idx_post_clip = np.rint(post_clip_colors[:, 0]).astype(np.int64)

    # Now run VecGridSample. It uses the same FNV hash so we can reproduce the
    # cell key for every post-clip line and identify per-cell survivors.
    dd = VecGridSample(
        grid_size=grid_size, hash_type="fnv", mode="test", return_grid_coord=True
    )(dd)
    post_grid_colors = np.asarray(dd["svg_data"].colors)
    # survivors' index inside the post-clip array (= row_idx encoded again,
    # but post-clip row_idx == its position 0..N1-1 since we built passenger
    # 0..n-1 and VecClipping just subsets it — but the SURVIVOR's passenger
    # value is the original 0..n-1 idx into lines_norm). To get its position
    # in the post-clip array, search the post_clip_colors for matches.
    survivor_pre_clip = np.rint(post_grid_colors[:, 0]).astype(
        np.int64
    )  # (N2,) into pre-clip
    # Build map pre_clip -> post_clip position
    pre_to_post = {int(idx_post_clip[i]): i for i in range(idx_post_clip.size)}
    idx_grid_in_post = np.asarray(
        [pre_to_post[int(x)] for x in survivor_pre_clip], dtype=np.int64
    )

    # Recompute cell keys on the post-clip coords. Must mirror VecGridSample
    # byte-for-byte: representative_coord = float32 coord.mean(); then
    # `coord / np.array(grid_size)` upcasts the divisor to float64 implicitly,
    # so the division runs in float64. Forcing the division to float32 here
    # caused near-cell-boundary lines to round into a different cell than the
    # original gridsample run → `cell_to_npz` lookup misses with KeyError on
    # ~5% of windows in the audited subset.
    rep = post_clip_coords.mean(axis=1).astype(np.float32)
    gc = np.floor(rep / np.array(grid_size)).astype(np.int64)
    gc -= gc.min(0)
    keys = _fnv_hash_vec(gc)  # (N1,)

    # Survivors live at post-clip positions idx_grid_in_post; their NPZ position
    # is just their position in idx_grid_in_post.
    cell_to_npz: Dict[int, int] = {}
    for npz_pos in range(idx_grid_in_post.size):
        cell_to_npz[int(keys[idx_grid_in_post[npz_pos]])] = npz_pos

    npz_pos_per_post = np.empty(idx_post_clip.size, dtype=np.int64)
    for i in range(idx_post_clip.size):
        npz_pos_per_post[i] = cell_to_npz[int(keys[i])]

    return idx_post_clip, idx_grid_in_post, npz_pos_per_post


def load_window_global_full(
    filename: str,
    npz_dir: str,
    cache_dir: str,
    gt_dir: str,
    split: str = "test",
    scene_bound: float | None = None,
    grid_size: float = 0.01,
    min_instance_ratio: float = 0.3,
) -> Dict:
    """Like `load_window_global`, but returns the FULL post-VecClipping line
    set (no grid sub-sampling). Each line inherits its predicted assignment
    from the grid cell's gridsample survivor.

    Extra keys vs `load_window_global`:
      n_post_clip          int  number of lines returned (>= NPZ.assign size)
      n_post_grid          int  NPZ.assign size (the model-input count)
      inherit_npz_pos      (n_post_clip,) int64  per line, position in NPZ whose
                            assignment it inherits
      idx_post_clip        (n_post_clip,) int64  indices into the original cache
                            coords array (so GT can be looked up per-line)
    """
    npz_path = os.path.join(npz_dir, f"{filename}.npz")
    cache_path = os.path.join(cache_dir, split, "cache_pkl", f"{filename}.pkl")
    gt_path = os.path.join(gt_dir, split, "gt_update_size", f"{filename}.json")

    npz = np.load(npz_path, allow_pickle=True)
    with open(cache_path, "rb") as f:
        cache = pickle.load(f)
    with open(gt_path, "r", encoding="utf-8") as f:
        gt_json = json.load(f)

    svg = cache["svg_arrays"]
    coords = np.asarray(svg["coords"], dtype=np.float32).reshape(-1, 2, 2)
    prim_ids_per_line = np.asarray(svg["primitive_ids"], dtype=np.int64)
    inst_per_prim = np.asarray(svg["instance_ids"], dtype=np.int64)
    sem_per_prim = np.asarray(svg["semantic_ids"], dtype=np.int64)

    crop_window = gt_json[0]["crop_window"]
    if scene_bound is None:
        scene_bound = float(npz["scene_bound"])
    half_f32 = np.float32(scene_bound / 2.0)
    origin_f32 = np.asarray(crop_window[:2], dtype=np.float32)
    lines_norm = ((coords - origin_f32) - half_f32) / half_f32

    primitive_lengths = np.asarray(
        svg.get("primitive_lengths", np.ones(len(sem_per_prim))),
        dtype=np.float32,
    )
    idx_post, idx_grid_in_post, npz_pos = _apply_clipping_with_inheritance(
        lines_norm,
        prim_ids_per_line,
        inst_per_prim,
        sem_per_prim,
        primitive_lengths,
        min_instance_ratio=min_instance_ratio,
        grid_size=grid_size,
    )

    n_npz = int(np.asarray(npz["assign_inst"]).size)
    if idx_grid_in_post.size != n_npz:
        raise RuntimeError(
            f"alignment mismatch for {filename}: post-grid N={idx_grid_in_post.size}, "
            f"NPZ N={n_npz}. (pre-clip lines={coords.shape[0]})"
        )

    # Lift post-clip lines back to mm CAD coords (float64).
    lines_post_norm = lines_norm[idx_post]
    lines_global = (
        lines_post_norm.astype(np.float64) * float(half_f32)
        + np.asarray(crop_window[:2], dtype=np.float64)
        + float(half_f32)
    )

    # Per-line predicted assignment (inherited from cell survivor).
    # NPZ stores `assign_sem` as 0-indexed physical class with -1 = unassigned.
    # The downstream `_sem_color` expects 1-indexed (0 = bg, 1..23 = fg), so
    # we shift +1 here. The same convention applies to all sem arrays we
    # forward from NPZ (assign_sem, pred_instance_labels, gt_instance_labels)
    # and to gt_sem (derived from cache.gt_arrays.semantic_id, also 0-indexed).
    # See SCENE_RENDER_DEMO.md §3.
    npz_assign_inst = np.asarray(npz["assign_inst"], dtype=np.int32)
    npz_assign_sem = np.asarray(npz["assign_sem"], dtype=np.int32)
    npz_seg_len = np.asarray(npz["seg_lengths"], dtype=np.float32)
    assign_inst = npz_assign_inst[npz_pos]
    assign_sem_raw = npz_assign_sem[npz_pos]
    assign_sem = np.where(assign_sem_raw >= 0, assign_sem_raw + 1, 0).astype(np.int32)
    # seg_lengths from NPZ is per-survivor; for full lines we recompute from
    # actual line geometry (much more accurate per-line).
    seg_diff = lines_global[:, 1] - lines_global[:, 0]
    seg_lengths = np.linalg.norm(seg_diff, axis=1).astype(np.float32)

    # Per-line GT: use cache.gt_arrays.semantic_id (per-instance, 0-indexed
    # physical class), NOT cache.svg_arrays.semantic_ids (per-primitive,
    # internal-library label). Broadcast via `instance_ids` LUT then +1.
    gt_inst = inst_per_prim[prim_ids_per_line[idx_post]].astype(np.int32)
    gt_inst_sem = np.asarray(cache["gt_arrays"]["semantic_id"], dtype=np.int32)
    gt_sem = np.zeros(idx_post.size, dtype=np.int32)
    fg_gt = gt_inst > 0
    if fg_gt.any():
        gt_sem[fg_gt] = gt_inst_sem[gt_inst[fg_gt] - 1] + 1

    # Per-instance pred masks: expand from (K, N_grid) -> (K, N_post_clip) via inheritance.
    pred_inst_masks_grid = np.asarray(npz["pred_instance_masks"], dtype=bool)
    pred_inst_masks = pred_inst_masks_grid[:, npz_pos]
    pred_inst_labels_raw = np.asarray(npz["pred_instance_labels"], dtype=np.int32)
    pred_inst_labels = np.where(
        pred_inst_labels_raw >= 0, pred_inst_labels_raw + 1, 0
    ).astype(np.int32)
    gt_inst_masks_grid = np.asarray(npz["gt_instance_masks"], dtype=bool)
    gt_inst_masks = gt_inst_masks_grid[:, npz_pos]
    gt_inst_labels_raw = np.asarray(npz["gt_instance_labels"], dtype=np.int32)
    gt_inst_labels = np.where(
        gt_inst_labels_raw >= 0, gt_inst_labels_raw + 1, 0
    ).astype(np.int32)

    # Interior margin per pred instance (using full-line endpoints).
    xmin, ymin, xmax, ymax = crop_window
    k_pred = pred_inst_masks.shape[0]
    margin_per_pred = np.zeros(k_pred, dtype=np.float64)
    for k in range(k_pred):
        m = pred_inst_masks[k]
        if not m.any():
            continue
        ep = lines_global[m].reshape(-1, 2)
        d = np.minimum.reduce(
            [
                ep[:, 0] - xmin,
                xmax - ep[:, 0],
                ep[:, 1] - ymin,
                ymax - ep[:, 1],
            ]
        )
        margin_per_pred[k] = float(d.max())

    return {
        "filename": filename,
        "crop_window": list(crop_window),
        "scene_bound": float(scene_bound),
        "lines_global": lines_global,
        "assign_inst": assign_inst,
        "assign_sem": assign_sem,
        "gt_inst": gt_inst,
        "gt_sem": gt_sem,
        "seg_lengths": seg_lengths,
        "pred_instance_labels": pred_inst_labels,
        "pred_instance_masks": pred_inst_masks,
        "gt_instance_labels": gt_inst_labels,
        "gt_instance_masks": gt_inst_masks,
        "interior_margin_per_pred": margin_per_pred,
        "idx_surviving": idx_post.astype(np.int64),  # post-clip → pre-clip indices
        "n_post_clip": int(idx_post.size),
        "n_post_grid": int(n_npz),
        "inherit_npz_pos": npz_pos,
    }


# ---------------------------------------------------------------------------- #
#  GT-only loader: no NPZ required. Reads cache + crop_window only, runs the
#  same VecClipping as the model would, lifts surviving lines back to mm. Used
#  for rendering scenes that have no predictions (e.g. raw DXFs not yet
#  inferred on this model).
# ---------------------------------------------------------------------------- #
def load_window_global_gt_only(
    filename: str,
    cache_dir: str,
    gt_dir: str,
    split: str = "test",
    scene_bound: float = 30000.0,
    min_instance_ratio: float = 0.3,
) -> Dict:
    """Like `load_window_global_full` but with no NPZ dependency. Returns the
    post-VecClipping lines in global mm coords + per-line GT inst/sem.

    Keys returned:
        filename, crop_window, scene_bound
        lines_global  (N, 2, 2) float64 mm
        gt_inst       (N,) int32  cache convention (-1 = bg)
        gt_sem        (N,) int32  shifted-to-NPZ convention (fg = 2..N+1, 0 = bg)
        seg_lengths   (N,) float32  per-line Euclidean length in mm
        n_post_clip   int
    """
    from datasets.transform import VecClipping
    from datasets.vec_data.industrycad.dataclass_define import SVGData

    cache_path = os.path.join(cache_dir, split, "cache_pkl", f"{filename}.pkl")
    gt_path = os.path.join(gt_dir, split, "gt_update_size", f"{filename}.json")
    with open(cache_path, "rb") as f:
        cache = pickle.load(f)
    with open(gt_path, "r", encoding="utf-8") as f:
        gt_json = json.load(f)

    svg = cache["svg_arrays"]
    coords = np.asarray(svg["coords"], dtype=np.float32).reshape(-1, 2, 2)
    prim_ids_per_line = np.asarray(svg["primitive_ids"], dtype=np.int64)
    inst_per_prim = np.asarray(svg["instance_ids"], dtype=np.int64)
    sem_per_prim = np.asarray(svg["semantic_ids"], dtype=np.int64)
    primitive_lengths = np.asarray(
        svg.get("primitive_lengths", np.ones(len(sem_per_prim))), dtype=np.float32
    )

    crop_window = gt_json[0]["crop_window"]
    half_f32 = np.float32(scene_bound / 2.0)
    origin_f32 = np.asarray(crop_window[:2], dtype=np.float32)
    lines_norm = ((coords - origin_f32) - half_f32) / half_f32

    n = lines_norm.shape[0]
    if n == 0:
        return {
            "filename": filename,
            "crop_window": list(crop_window),
            "scene_bound": float(scene_bound),
            "lines_global": np.empty((0, 2, 2), dtype=np.float64),
            "gt_inst": np.empty(0, dtype=np.int32),
            "gt_sem": np.empty(0, dtype=np.int32),
            "seg_lengths": np.empty(0, dtype=np.float32),
            "n_post_clip": 0,
        }

    row_idx = np.arange(n, dtype=np.float64)
    colors_passenger = np.zeros((n, 3), dtype=np.float64)
    colors_passenger[:, 0] = row_idx

    svg_obj = SVGData(
        viewBox=[0.0, 0.0, scene_bound, scene_bound],
        coords=lines_norm.astype(np.float32, copy=False),
        colors=colors_passenger,
        widths=np.ones(n, dtype=np.float32),
        layer_ids=np.zeros(n, dtype=np.int32),
        primitive_ids=prim_ids_per_line.astype(np.int32, copy=False),
        semantic_ids=sem_per_prim.astype(np.int32, copy=False),
        instance_ids=inst_per_prim.astype(np.int32, copy=False),
        primitive_lengths=primitive_lengths,
    )
    n_inst = int(inst_per_prim.size)
    dd = {
        "svg_data": svg_obj,
        "translation": np.zeros((n_inst, 2), dtype=np.float32),
        "size": np.ones((n_inst, 2), dtype=np.float32),
    }
    dd = VecClipping(
        clip_range=[-1, 1], min_instance_ratio=min_instance_ratio, update_size=True
    )(dd)
    if dd.get("_drop_sample", False):
        return {
            "filename": filename,
            "crop_window": list(crop_window),
            "scene_bound": float(scene_bound),
            "lines_global": np.empty((0, 2, 2), dtype=np.float64),
            "gt_inst": np.empty(0, dtype=np.int32),
            "gt_sem": np.empty(0, dtype=np.int32),
            "seg_lengths": np.empty(0, dtype=np.float32),
            "n_post_clip": 0,
        }

    post_clip_colors = np.asarray(dd["svg_data"].colors)
    idx_post = np.rint(post_clip_colors[:, 0]).astype(np.int64)

    lines_post_norm = lines_norm[idx_post]
    lines_global = (
        lines_post_norm.astype(np.float64) * float(half_f32)
        + np.asarray(crop_window[:2], dtype=np.float64)
        + float(half_f32)
    )

    gt_inst = inst_per_prim[prim_ids_per_line[idx_post]].astype(np.int32)
    # Read physical-class GT from `cache.gt_arrays.semantic_id` (per-instance,
    # 0-indexed). The old path read `cache.svg_arrays.semantic_ids`
    # (per-primitive) which is the model library's internal label, NOT the
    # physical class — that caused multi-instance class confusion in renders.
    # See COLOR_MAPPING_PREFIX.md (in this exp's scene_gt_5/) for the audit.
    gt_inst_sem = np.asarray(cache["gt_arrays"]["semantic_id"], dtype=np.int32)
    gt_sem = np.zeros(idx_post.size, dtype=np.int32)
    fg = gt_inst > 0
    if fg.any():
        # `instance_ids` in cache are 1-indexed (-1 / 0 = bg); gt_arrays is
        # 0-indexed by instance row. After lookup we +1 again so the result
        # is 1-indexed (=`cls + 1`) — matches the downstream `_sem_color`
        # convention (s = 0 means bg, s = 1..23 means fg cls 0..22).
        gt_sem[fg] = gt_inst_sem[gt_inst[fg] - 1] + 1

    seg_diff = lines_global[:, 1] - lines_global[:, 0]
    seg_lengths = np.linalg.norm(seg_diff, axis=1).astype(np.float32)

    return {
        "filename": filename,
        "crop_window": list(crop_window),
        "scene_bound": float(scene_bound),
        "lines_global": lines_global,
        "gt_inst": gt_inst,
        "gt_sem": gt_sem,
        "seg_lengths": seg_lengths,
        "n_post_clip": int(idx_post.size),
        # For compatibility with code paths that expect these (dedup will ignore them when empty):
        "assign_inst": np.full(idx_post.size, -1, dtype=np.int32),
        "assign_sem": np.full(idx_post.size, -1, dtype=np.int32),
        "pred_instance_labels": np.zeros(0, dtype=np.int32),
        "pred_instance_masks": np.zeros((0, idx_post.size), dtype=bool),
        "gt_instance_labels": np.zeros(0, dtype=np.int32),
        "gt_instance_masks": np.zeros((0, idx_post.size), dtype=bool),
        "interior_margin_per_pred": np.zeros(0, dtype=np.float64),
    }


def group_windows_by_scene_from_cache(
    cache_dir: str, split: str = "test"
) -> Dict[str, List[str]]:
    """Like `group_windows_by_scene` but discovers windows by scanning the
    dataset's `<cache_dir>/<split>/cache_pkl/` instead of an NPZ dir. Lets us
    render scenes that have no predictions on a particular model checkpoint."""
    pkl_dir = os.path.join(cache_dir, split, "cache_pkl")
    groups: Dict[str, List[Tuple[int, str]]] = defaultdict(list)
    for fname in os.listdir(pkl_dir):
        if not fname.endswith(".pkl"):
            continue
        stem = fname[:-4]
        m = _FILENAME_RE.match(stem)
        if m is None:
            continue
        groups[m.group(1)].append((int(m.group(2)), stem))
    return {s: [stem for _, stem in sorted(items)] for s, items in groups.items()}


# ---------------------------------------------------------------------------- #
#  Per-window loader
# ---------------------------------------------------------------------------- #
def load_window_global(
    filename: str,
    npz_dir: str,
    cache_dir: str,
    gt_dir: str,
    split: str = "test",
    scene_bound: float | None = None,
    grid_size: float = 0.01,
    min_instance_ratio: float = 0.3,
) -> Dict:
    """Load one window and return its lines in scene-global mm CAD coords plus
    per-segment predicted/gt assignments.

    Returns dict with these keys:
        filename               : str
        crop_window            : list[4]  [xmin, ymin, xmax, ymax] mm
        scene_bound            : float
        lines_global           : (N, 2, 2) float64, mm CAD coords
        assign_inst            : (N,) int32  window-local pred instance, -1 unassigned
        assign_sem             : (N,) int32  pred semantic (model conv), -1 unassigned
        gt_inst                : (N,) int32  from cache.svg_arrays
        gt_sem                 : (N,) int32  from cache.svg_arrays
        seg_lengths            : (N,) float32
        pred_instance_labels   : (K_pred,) int32  per-instance pred sem (model conv)
        pred_instance_masks    : (K_pred, N) bool
        gt_instance_labels     : (K_gt,) int32
        gt_instance_masks      : (K_gt, N) bool
        interior_margin_per_pred : (K_pred,) float64  per-instance min distance
                                   from any of its line endpoints to the 4
                                   crop_window edges (mm). Larger = the window
                                   saw more of the instance's surroundings.
        idx_surviving          : (N,) int64  indices into the cache's full
                                   coords array; lets you map back to GT
    """
    npz_path = os.path.join(npz_dir, f"{filename}.npz")
    cache_path = os.path.join(cache_dir, split, "cache_pkl", f"{filename}.pkl")
    gt_path = os.path.join(gt_dir, split, "gt_update_size", f"{filename}.json")

    npz = np.load(npz_path, allow_pickle=True)
    with open(cache_path, "rb") as f:
        cache = pickle.load(f)
    with open(gt_path, "r", encoding="utf-8") as f:
        gt_json = json.load(f)

    svg = cache["svg_arrays"]
    # Replicate the dataset's float32 normalisation (`PrimitiveDataset._transform`):
    # coords[mm, float32] - crop_window[:2] - half -> /half. Doing the whole
    # chain in float32 is load-bearing — float64 here desyncs one line on a
    # tiny minority of windows when a near-boundary mean falls in a different
    # grid cell after rounding.
    coords = np.asarray(svg["coords"], dtype=np.float32).reshape(-1, 2, 2)
    prim_ids_per_line = np.asarray(svg["primitive_ids"], dtype=np.int64)
    inst_per_prim = np.asarray(svg["instance_ids"], dtype=np.int64)
    sem_per_prim = np.asarray(svg["semantic_ids"], dtype=np.int64)

    crop_window = gt_json[0]["crop_window"]
    if scene_bound is None:
        scene_bound = float(npz["scene_bound"])
    half_f32 = np.float32(scene_bound / 2.0)
    origin_f32 = np.asarray(crop_window[:2], dtype=np.float32)

    lines_norm = ((coords - origin_f32) - half_f32) / half_f32  # float32 throughout

    primitive_lengths = np.asarray(
        svg.get("primitive_lengths", np.ones(len(sem_per_prim))), dtype=np.float32
    )
    idx = _apply_val_transforms(
        lines_norm,
        prim_ids_per_line,
        inst_per_prim,
        sem_per_prim,
        primitive_lengths=primitive_lengths,
        min_instance_ratio=min_instance_ratio,
        grid_size=grid_size,
    )

    n_npz = int(np.asarray(npz["assign_inst"]).size)
    if idx.size != n_npz:
        raise RuntimeError(
            f"alignment mismatch for {filename}: post-pipeline N={idx.size}, "
            f"NPZ N={n_npz}. (pre-clip lines={coords.shape[0]})"
        )

    # Lift surviving lines back to absolute mm CAD coords. Use float64 here so
    # the global table can range cleanly across a 100-metre scene without
    # losing sub-mm precision near the far corners.
    lines_global = (
        lines_norm[idx].astype(np.float64) * float(half_f32)
        + np.asarray(crop_window[:2], dtype=np.float64)
        + float(half_f32)
    )

    assign_inst = np.asarray(npz["assign_inst"], dtype=np.int32)
    # NPZ stores sem as 0-indexed physical class with -1 = bg/unassigned.
    # Shift +1 to match `_sem_color`'s 1-indexed convention (bg = 0, fg = 1..23).
    # See SCENE_RENDER_DEMO.md §3.
    assign_sem_raw = np.asarray(npz["assign_sem"], dtype=np.int32)
    assign_sem = np.where(assign_sem_raw >= 0, assign_sem_raw + 1, 0).astype(np.int32)
    seg_lengths = np.asarray(npz["seg_lengths"], dtype=np.float32)
    pred_inst_masks = np.asarray(npz["pred_instance_masks"], dtype=bool)
    pred_inst_labels_raw = np.asarray(npz["pred_instance_labels"], dtype=np.int32)
    pred_inst_labels = np.where(
        pred_inst_labels_raw >= 0, pred_inst_labels_raw + 1, 0
    ).astype(np.int32)
    gt_inst_masks = np.asarray(npz["gt_instance_masks"], dtype=bool)
    gt_inst_labels_raw = np.asarray(npz["gt_instance_labels"], dtype=np.int32)
    gt_inst_labels = np.where(
        gt_inst_labels_raw >= 0, gt_inst_labels_raw + 1, 0
    ).astype(np.int32)
    gt_inst = np.asarray(npz["seg_gt_inst"], dtype=np.int32)
    gt_sem_raw = np.asarray(npz["seg_gt_sem"], dtype=np.int32)
    gt_sem = np.where(gt_sem_raw >= 0, gt_sem_raw + 1, 0).astype(np.int32)

    # Interior margin per predicted instance: distance from each contributing
    # line endpoint to the nearest crop_window edge (mm); take MAX across the
    # instance's endpoints (the most-interior endpoint is most informative —
    # we want to know how deep this instance lives inside the window).
    xmin, ymin, xmax, ymax = crop_window
    k_pred = pred_inst_masks.shape[0]
    margin_per_pred = np.zeros(k_pred, dtype=np.float64)
    for k in range(k_pred):
        m = pred_inst_masks[k]
        if not m.any():
            continue
        ep = lines_global[m].reshape(-1, 2)  # (2*n_seg, 2)
        d = np.minimum.reduce(
            [
                ep[:, 0] - xmin,
                xmax - ep[:, 0],
                ep[:, 1] - ymin,
                ymax - ep[:, 1],
            ]
        )
        margin_per_pred[k] = float(d.max())

    return {
        "filename": filename,
        "crop_window": list(crop_window),
        "scene_bound": float(scene_bound),
        "lines_global": lines_global,
        "assign_inst": assign_inst,
        "assign_sem": assign_sem,
        "gt_inst": gt_inst,
        "gt_sem": gt_sem,
        "seg_lengths": seg_lengths,
        "pred_instance_labels": pred_inst_labels,
        "pred_instance_masks": pred_inst_masks,
        "gt_instance_labels": gt_inst_labels,
        "gt_instance_masks": gt_inst_masks,
        "interior_margin_per_pred": margin_per_pred,
        "idx_surviving": idx,
    }


# ---------------------------------------------------------------------------- #
#  Scene grouping
# ---------------------------------------------------------------------------- #
def group_windows_by_scene(npz_dir: str) -> Dict[str, List[str]]:
    """Walk an npz dir, group files by their scene name parsed from the filename.

    Returns dict[scene_name] = sorted list of window filenames (stem, no .npz).
    """
    groups: Dict[str, List[Tuple[int, str]]] = defaultdict(list)
    for fname in os.listdir(npz_dir):
        if not fname.endswith(".npz"):
            continue
        stem = fname[:-4]
        m = _FILENAME_RE.match(stem)
        if m is None:
            continue
        scene = m.group(1)
        win_idx = int(m.group(2))
        groups[scene].append((win_idx, stem))
    return {s: [stem for _, stem in sorted(items)] for s, items in groups.items()}


# ---------------------------------------------------------------------------- #
#  Cross-window line dedup
# ---------------------------------------------------------------------------- #
def dedup_lines(
    window_datas: List[Dict],
    eps_mm: float = 1.0,
) -> Dict:
    """Concatenate per-window lines into one scene-level table, deduplicating
    lines that fall in window-overlap zones.

    Conflict resolution when the same canonical line appears in multiple
    windows: the contender with the larger `owner_score` wins. Score is
    `interior_margin_per_pred[assign_inst]` (0 for unassigned predictions).

    Args:
        window_datas: list of dicts returned by `load_window_global`. All must
            share the same scene_bound.
        eps_mm: endpoint quantisation for canonical hashing (mm). 1.0 means
            two endpoints within 1 mm of each other in CAD space collapse.
            Endpoints are sorted within each line before hashing so reversed
            orientations collapse together.

    Returns dict:
        scene_lines (N_scene, 2, 2)  unique scene lines, mm
        assign_inst_local (N_scene,) winning window's local pred instance id
        assign_sem (N_scene,)        winning window's pred sem
        gt_inst (N_scene,)           GT inst (cache convention, -1 = bg)
        gt_sem (N_scene,)            GT sem
        seg_lengths (N_scene,)
        owner_window_idx (N_scene,)  index into window_datas of the winner
        owner_score (N_scene,)       interior margin of the winner
        dup_count (N_scene,)         how many windows contributed this line
        n_input_total                int, sum of per-window line counts
    """
    if not window_datas:
        return {
            "scene_lines": np.empty((0, 2, 2), dtype=np.float64),
            "assign_inst_local": np.empty(0, dtype=np.int32),
            "assign_sem": np.empty(0, dtype=np.int32),
            "gt_inst": np.empty(0, dtype=np.int32),
            "gt_sem": np.empty(0, dtype=np.int32),
            "seg_lengths": np.empty(0, dtype=np.float32),
            "owner_window_idx": np.empty(0, dtype=np.int32),
            "owner_score": np.empty(0, dtype=np.float64),
            "dup_count": np.empty(0, dtype=np.int32),
            "n_input_total": 0,
            "input_to_scene_per_window": [],
        }

    # ---- canonical hashing across all windows ---- #
    # Quantise each endpoint to integer grid at `eps_mm`, then sort the two
    # endpoints within each line so reversed orientations collapse.
    key_to_first: Dict[Tuple[int, int, int, int], int] = {}
    # Per scene-line state arrays, grown as we discover new keys.
    scene_lines: List[np.ndarray] = []
    a_inst: List[int] = []
    a_sem: List[int] = []
    g_inst: List[int] = []
    g_sem: List[int] = []
    s_len: List[float] = []
    own_w: List[int] = []
    own_score: List[float] = []
    dup: List[int] = []

    n_total = 0
    input_to_scene_per_window: List[np.ndarray] = []
    for w_idx, wd in enumerate(window_datas):
        lines = wd["lines_global"]
        n_total += lines.shape[0]
        if lines.shape[0] == 0:
            input_to_scene_per_window.append(np.empty(0, dtype=np.int64))
            continue
        # quantise + canonicalise per-line
        q = np.round(lines / eps_mm).astype(np.int64)  # (N, 2, 2)
        # sort endpoints lex by (x, y) within each line
        # cheap stable: for each row, pick the smaller endpoint first
        e0 = q[:, 0]
        e1 = q[:, 1]
        swap = (e0[:, 0] > e1[:, 0]) | ((e0[:, 0] == e1[:, 0]) & (e0[:, 1] > e1[:, 1]))
        a = np.where(swap[:, None], e1, e0)
        b = np.where(swap[:, None], e0, e1)
        keys = np.empty((q.shape[0], 4), dtype=np.int64)
        keys[:, 0] = a[:, 0]
        keys[:, 1] = a[:, 1]
        keys[:, 2] = b[:, 0]
        keys[:, 3] = b[:, 1]

        a_inst_w = wd["assign_inst"]
        a_sem_w = wd["assign_sem"]
        g_inst_w = wd["gt_inst"]
        g_sem_w = wd["gt_sem"]
        s_len_w = wd["seg_lengths"]
        margin_w = wd["interior_margin_per_pred"]  # (K_pred,)

        i_to_s = np.empty(q.shape[0], dtype=np.int64)
        k_pred_w = int(margin_w.size)
        for i in range(q.shape[0]):
            k = (int(keys[i, 0]), int(keys[i, 1]), int(keys[i, 2]), int(keys[i, 3]))
            inst_id = int(a_inst_w[i])
            # Guard against `assign_inst` indices that exceed the per-instance
            # array size — happens on some windows (proj_from_ins script may
            # leak indices past the end of `pred_instance_labels`). Treat as
            # unassigned in that case.
            if inst_id < 0 or inst_id >= k_pred_w:
                inst_id = -1
                score = 0.0
            else:
                score = float(margin_w[inst_id])
            if k in key_to_first:
                j = key_to_first[k]
                i_to_s[i] = j
                dup[j] += 1
                # tie-break: assigned > unassigned, then higher score
                cur_assigned = a_inst[j] >= 0
                new_assigned = inst_id >= 0
                if (new_assigned and not cur_assigned) or (
                    new_assigned == cur_assigned and score > own_score[j]
                ):
                    a_inst[j] = inst_id
                    a_sem[j] = int(a_sem_w[i])
                    own_w[j] = w_idx
                    own_score[j] = score
                    s_len[j] = float(s_len_w[i])
                    # keep GT (consistent across windows; refresh anyway)
                    g_inst[j] = int(g_inst_w[i])
                    g_sem[j] = int(g_sem_w[i])
            else:
                new_idx = len(scene_lines)
                key_to_first[k] = new_idx
                i_to_s[i] = new_idx
                scene_lines.append(lines[i])
                a_inst.append(inst_id)
                a_sem.append(int(a_sem_w[i]))
                g_inst.append(int(g_inst_w[i]))
                g_sem.append(int(g_sem_w[i]))
                s_len.append(float(s_len_w[i]))
                own_w.append(w_idx)
                own_score.append(score)
                dup.append(1)
        input_to_scene_per_window.append(i_to_s)

    return {
        "scene_lines": (
            np.asarray(scene_lines, dtype=np.float64)
            if scene_lines
            else np.empty((0, 2, 2), dtype=np.float64)
        ),
        "assign_inst_local": np.asarray(a_inst, dtype=np.int32),
        "assign_sem": np.asarray(a_sem, dtype=np.int32),
        "gt_inst": np.asarray(g_inst, dtype=np.int32),
        "gt_sem": np.asarray(g_sem, dtype=np.int32),
        "seg_lengths": np.asarray(s_len, dtype=np.float32),
        "owner_window_idx": np.asarray(own_w, dtype=np.int32),
        "owner_score": np.asarray(own_score, dtype=np.float64),
        "dup_count": np.asarray(dup, dtype=np.int32),
        "n_input_total": int(n_total),
        "input_to_scene_per_window": input_to_scene_per_window,
    }


# ---------------------------------------------------------------------------- #
#  Cross-window instance stitching (Jaccard + union-find)
# ---------------------------------------------------------------------------- #
class _UF:
    """Tiny union-find with path compression."""

    def __init__(self):
        self.p: Dict[Tuple[int, int], Tuple[int, int]] = {}

    def find(self, x):
        if self.p.get(x, x) == x:
            self.p[x] = x
            return x
        r = self.find(self.p[x])
        self.p[x] = r
        return r

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[ra] = rb


def stitch_instances(
    merged: Dict,
    window_datas: List[Dict],
    jaccard_thresh: float = 0.3,
    min_lines: int = 1,
) -> Dict:
    """Stitch per-window predicted instances into scene-level global instances.

    A pair of (window_a, local_inst_a) and (window_b, local_inst_b) is unioned
    when their scene-line sets satisfy Jaccard >= `jaccard_thresh`. Edges are
    only considered for pairs that share at least one scene line — discovered
    by inverting input_to_scene_per_window — so the candidate count is small.

    Args:
        merged: output of `dedup_lines`
        window_datas: same list passed to `dedup_lines`
        jaccard_thresh: float in (0, 1]. Lower = more aggressive stitching.
        min_lines: drop nodes with fewer than this many scene lines before
            stitching (handy for filtering tiny noise predictions). 1 = keep
            all assigned predictions.

    Returns dict (also patches into `merged` in-place for convenience):
        assign_inst_global  (N_scene,) int32  global instance id per scene
                            line, -1 = bg
        assign_sem_global   (N_scene,) int32  canonical sem id per scene line
                            (the contributor with the largest interior margin
                            wins). Falls back to scene line's existing
                            assign_sem for bg lines.
        n_global_instances  int
        instances           list of dicts (one per global inst):
            global_id, sem_id, n_lines, contributors=[(w_idx, local_inst), ...],
            interior_margin_max
    """
    n_scene = merged["scene_lines"].shape[0]
    if n_scene == 0:
        return {
            "assign_inst_global": np.empty(0, dtype=np.int32),
            "assign_sem_global": np.empty(0, dtype=np.int32),
            "n_global_instances": 0,
            "instances": [],
        }

    # ---- 1. build per-(w, k) -> set of scene_line indices ---- #
    node_lines: Dict[Tuple[int, int], set] = {}
    for w_idx, wd in enumerate(window_datas):
        i_to_s = merged["input_to_scene_per_window"][w_idx]
        a_inst = wd["assign_inst"]
        for i in range(i_to_s.size):
            k = int(a_inst[i])
            if k < 0:
                continue
            node = (w_idx, k)
            s = node_lines.get(node)
            if s is None:
                s = set()
                node_lines[node] = s
            s.add(int(i_to_s[i]))

    if min_lines > 1:
        node_lines = {n: s for n, s in node_lines.items() if len(s) >= min_lines}

    # ---- 2. invert to scene_line -> list of nodes, gather candidate pairs ---- #
    line_to_nodes: Dict[int, List[Tuple[int, int]]] = {}
    for node, s in node_lines.items():
        for sline in s:
            line_to_nodes.setdefault(sline, []).append(node)

    candidates: set = set()
    for sline, nodes in line_to_nodes.items():
        if len(nodes) < 2:
            continue
        for i in range(len(nodes)):
            for j in range(i + 1, len(nodes)):
                a, b = nodes[i], nodes[j]
                if a == b:
                    continue
                pair = (a, b) if a < b else (b, a)
                candidates.add(pair)

    # ---- 3. Jaccard test + union find ---- #
    uf = _UF()
    for a, b in candidates:
        A, B = node_lines[a], node_lines[b]
        if len(A) == 0 or len(B) == 0:
            continue
        # Iterate the smaller set for the intersection (cheap |A ∩ B|).
        if len(A) > len(B):
            A, B = B, A
        inter = sum(1 for x in A if x in B)
        if inter == 0:
            continue
        union = len(A) + len(B) - inter
        if inter / union >= jaccard_thresh:
            uf.union(a, b)

    # ---- 4. assign global ids in stable order ---- #
    global_id_map: Dict[Tuple[int, int], int] = {}
    nodes_sorted = sorted(node_lines.keys())  # deterministic id assignment
    for node in nodes_sorted:
        r = uf.find(node)
        if r not in global_id_map:
            global_id_map[r] = len(global_id_map)
    n_global = len(global_id_map)

    # ---- 5. write per-scene-line global instance id ---- #
    own_w = merged["owner_window_idx"]
    own_k = merged["assign_inst_local"]
    assign_inst_global = np.full(n_scene, -1, dtype=np.int32)
    for s in range(n_scene):
        k = int(own_k[s])
        if k < 0:
            continue
        node = (int(own_w[s]), k)
        if node in node_lines:  # may have been filtered by min_lines
            assign_inst_global[s] = global_id_map[uf.find(node)]

    # ---- 6. per global instance: dominant sem (by max interior margin) ---- #
    # Aggregate contributors per global id.
    contrib: Dict[int, List[Tuple[int, int]]] = {g: [] for g in range(n_global)}
    for node in nodes_sorted:
        g = global_id_map[uf.find(node)]
        contrib[g].append(node)

    instances: List[Dict] = []
    sem_by_g = np.full(n_global, -1, dtype=np.int32)
    margin_by_g = np.zeros(n_global, dtype=np.float64)
    for g in range(n_global):
        best_margin = -1.0
        best_sem = -1
        n_lines_g = 0
        all_lines: set = set()
        for w_idx, k in contrib[g]:
            n_lines_g += len(node_lines[(w_idx, k)])
            all_lines |= node_lines[(w_idx, k)]
            wd = window_datas[w_idx]
            # Defensive: some windows (proj_from_ins script edge case on
            # train-split inference) have assign_inst values ≥ K_pred. Skip
            # those contributors — same guard as in `dedup_lines`.
            margin_arr = wd["interior_margin_per_pred"]
            sem_arr = wd["pred_instance_labels"]
            if k < 0 or k >= margin_arr.size or k >= sem_arr.size:
                continue
            margin = float(margin_arr[k])
            sem = int(sem_arr[k])
            if margin > best_margin:
                best_margin = margin
                best_sem = sem
        sem_by_g[g] = best_sem
        margin_by_g[g] = best_margin
        instances.append(
            {
                "global_id": g,
                "sem_id": best_sem,
                "n_lines": len(all_lines),
                "contributors": list(contrib[g]),
                "interior_margin_max": best_margin,
            }
        )

    # canonical sem per scene line; bg lines keep their existing assign_sem
    assign_sem_global = merged["assign_sem"].copy()
    fg_mask = assign_inst_global >= 0
    assign_sem_global[fg_mask] = sem_by_g[assign_inst_global[fg_mask]]

    out = {
        "assign_inst_global": assign_inst_global,
        "assign_sem_global": assign_sem_global,
        "n_global_instances": n_global,
        "instances": instances,
    }
    # convenience: also write into merged dict
    merged.update(out)
    return out


# ---------------------------------------------------------------------------- #
#  Plan B: bbox-based 2nd-pass NMS after line-set Jaccard stitching
# ---------------------------------------------------------------------------- #
def _bbox_for_lines(lines):
    """Return (xmin, ymin, xmax, ymax) of a (N, 2, 2) line array."""
    pts = lines.reshape(-1, 2)
    return (
        float(pts[:, 0].min()),
        float(pts[:, 1].min()),
        float(pts[:, 0].max()),
        float(pts[:, 1].max()),
    )


def _bbox_iou(a, b):
    ax0, ay0, ax1, ay1 = a
    bx0, by0, bx1, by1 = b
    ix0 = max(ax0, bx0)
    iy0 = max(ay0, by0)
    ix1 = min(ax1, bx1)
    iy1 = min(ay1, by1)
    iw = max(0.0, ix1 - ix0)
    ih = max(0.0, iy1 - iy0)
    inter = iw * ih
    aa = max(0.0, ax1 - ax0) * max(0.0, ay1 - ay0)
    bb = max(0.0, bx1 - bx0) * max(0.0, by1 - by0)
    union = aa + bb - inter
    return (inter / union) if union > 0 else 0.0, inter, aa, bb


def stitch_with_bbox_nms(
    merged: Dict,
    window_datas: List[Dict],
    jaccard_thresh: float = 0.3,
    same_class_bbox_iou: float = 0.1,
    cross_class_bbox_iou: float = 0.3,
    nested_size_ratio: float = 2.0,
    nested_coverage: float = 0.7,
) -> Dict:
    """Plan B: run line-set Jaccard stitching first (same as `stitch_instances`),
    then do two bbox-IoU passes on the surviving global instances:

      Pass A — same-class merge:
        union-find on instances of identical canonical sem_id with
        bbox_IoU >= same_class_bbox_iou.

      Pass B — cross-class NMS:
        Walk instances in descending order of (interior_margin_max, n_lines).
        For each, check already-kept entries for cross-class overlap. Suppress
        if bbox_IoU(loser, kept) >= cross_class_bbox_iou AND NOT nested
        geometry (size_ratio >= nested_size_ratio AND
        min(inter / area_a, inter / area_b) >= nested_coverage).

    Returns same shape as `stitch_instances` (writes back into `merged`).
    """
    # ---- 1. line-set Jaccard stitching (reuse) ---- #
    st = stitch_instances(merged, window_datas, jaccard_thresh=jaccard_thresh)
    inst_global = st["assign_inst_global"].copy()
    sem_global = st["assign_sem_global"].copy()
    instances = list(st["instances"])
    n_global = st["n_global_instances"]
    if n_global == 0:
        merged.update(
            {
                "assign_inst_global": inst_global,
                "assign_sem_global": sem_global,
                "n_global_instances": 0,
                "instances": [],
                "stage": "bbox_nms",
            }
        )
        return merged

    scene_lines = merged["scene_lines"]

    # bbox + size per inst from its scene lines
    bboxes = np.zeros((n_global, 4), dtype=np.float64)
    sizes = np.zeros(n_global, dtype=np.float64)
    n_lines_per_inst = np.zeros(n_global, dtype=np.int64)
    margin_per_inst = np.zeros(n_global, dtype=np.float64)
    sem_per_inst = np.full(n_global, -1, dtype=np.int32)
    for g in range(n_global):
        mask = inst_global == g
        if not mask.any():
            continue
        bboxes[g] = _bbox_for_lines(scene_lines[mask])
        sizes[g] = max(0.0, bboxes[g, 2] - bboxes[g, 0]) * max(
            0.0, bboxes[g, 3] - bboxes[g, 1]
        )
        n_lines_per_inst[g] = int(mask.sum())
        margin_per_inst[g] = float(instances[g]["interior_margin_max"])
        sem_per_inst[g] = int(instances[g]["sem_id"])

    # ---- 2. Pass A: same-class bbox-IoU union find ---- #
    uf = _UF()
    # Bucket by sem class to limit pairs
    by_class: Dict[int, List[int]] = {}
    for g in range(n_global):
        by_class.setdefault(int(sem_per_inst[g]), []).append(g)
    for sem, ids in by_class.items():
        if sem < 0 or len(ids) < 2:
            continue
        for i in range(len(ids)):
            a = ids[i]
            for j in range(i + 1, len(ids)):
                b = ids[j]
                iou, _, _, _ = _bbox_iou(bboxes[a], bboxes[b])
                if iou >= same_class_bbox_iou:
                    uf.union((a, 0), (b, 0))

    # collapse same-class ids
    new_id_of_old: Dict[int, int] = {}
    new_ids: List[int] = []
    for g in range(n_global):
        r = uf.find((g, 0))
        if r not in new_id_of_old:
            new_id_of_old[r] = len(new_ids)
            new_ids.append(g)
    n_after_A = len(new_ids)

    # build "after pass A" inst arrays: merged bbox / sem / margin / n_lines
    inst_global_A = np.full_like(inst_global, -1)
    fg = inst_global >= 0
    inst_global_A[fg] = np.asarray(
        [new_id_of_old[uf.find((int(g), 0))] for g in inst_global[fg]], dtype=np.int32
    )
    bboxes_A = np.zeros((n_after_A, 4), dtype=np.float64)
    sem_A = np.full(n_after_A, -1, dtype=np.int32)
    margin_A = np.zeros(n_after_A, dtype=np.float64)
    n_lines_A = np.zeros(n_after_A, dtype=np.int64)
    contributors_A: List[List[int]] = [[] for _ in range(n_after_A)]
    for old_g in range(n_global):
        new_g = new_id_of_old[uf.find((old_g, 0))]
        contributors_A[new_g].append(old_g)
    for new_g in range(n_after_A):
        mask = inst_global_A == new_g
        if not mask.any():
            continue
        bboxes_A[new_g] = _bbox_for_lines(scene_lines[mask])
        n_lines_A[new_g] = int(mask.sum())
        # pick the contributor's sem and margin from the highest-margin contributor
        best = max(contributors_A[new_g], key=lambda g: margin_per_inst[g])
        sem_A[new_g] = sem_per_inst[best]
        margin_A[new_g] = margin_per_inst[best]

    # ---- 3. Pass B: cross-class NMS ---- #
    order = sorted(range(n_after_A), key=lambda g: (-margin_A[g], -n_lines_A[g]))
    kept: List[int] = []
    suppressed = np.zeros(n_after_A, dtype=bool)
    for g in order:
        a_box = bboxes_A[g]
        a_sem = sem_A[g]
        ok = True
        for k in kept:
            if sem_A[k] == a_sem:
                continue  # same-class already handled in pass A
            iou, inter, area_a, area_b = _bbox_iou(a_box, bboxes_A[k])
            if iou < cross_class_bbox_iou:
                continue
            # nested guard
            if area_a > 0 and area_b > 0:
                size_ratio = max(area_a, area_b) / min(area_a, area_b)
                min_cov = inter / min(area_a, area_b)
                if size_ratio >= nested_size_ratio and min_cov >= nested_coverage:
                    continue  # legitimately nested, don't suppress
            ok = False
            break
        if ok:
            kept.append(g)
        else:
            suppressed[g] = True

    # ---- 4. relabel scene lines & build instances ---- #
    keep_id_of_old: Dict[int, int] = {}
    for new_g in kept:
        keep_id_of_old[new_g] = len(keep_id_of_old)
    n_final = len(keep_id_of_old)
    inst_final = np.full_like(inst_global_A, -1)
    sem_final = sem_global.copy()
    fg2 = inst_global_A >= 0
    keep_arr = np.asarray(
        [keep_id_of_old.get(int(g), -1) for g in inst_global_A[fg2]], dtype=np.int32
    )
    inst_final[fg2] = keep_arr
    bg2 = (
        inst_final < 0
    )  # both originally bg + just-suppressed → fall back to dedup sem
    sem_final[bg2] = merged["assign_sem"][bg2]
    fg_final = inst_final >= 0
    # canonical sem propagates from pass-A semantics
    sem_lookup = np.array([sem_A[g] for g in kept] + [-1], dtype=np.int32)
    sem_final[fg_final] = sem_lookup[inst_final[fg_final]]

    final_instances: List[Dict] = []
    for k_new, g_old in enumerate(kept):
        final_instances.append(
            {
                "global_id": k_new,
                "sem_id": int(sem_A[g_old]),
                "n_lines": int(n_lines_A[g_old]),
                "interior_margin_max": float(margin_A[g_old]),
                "contributors_from_A": [int(x) for x in contributors_A[g_old]],
            }
        )

    merged.update(
        {
            "assign_inst_global": inst_final,
            "assign_sem_global": sem_final,
            "n_global_instances": n_final,
            "instances": final_instances,
            "stage": "bbox_nms",
            "n_after_jaccard": int(n_global),
            "n_after_same_class_bbox": int(n_after_A),
            "n_after_cross_class_nms": int(n_final),
        }
    )
    return {
        "assign_inst_global": inst_final,
        "assign_sem_global": sem_final,
        "n_global_instances": n_final,
        "instances": final_instances,
        "n_after_jaccard": int(n_global),
        "n_after_same_class_bbox": int(n_after_A),
        "n_after_cross_class_nms": int(n_final),
    }
